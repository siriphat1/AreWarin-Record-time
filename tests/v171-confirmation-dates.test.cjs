const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const code=fs.readFileSync(path.join(__dirname,'../assets/app.js'),'utf8');
const mem=new Map(),mockModal={innerHTML:''};
const context=vm.createContext({window:{TUTOR_CONFIG:{}},document:{readyState:'loading',addEventListener(){},querySelector:s=>s==='#modal-root'?mockModal:null},localStorage:{getItem:k=>mem.get(k)||null,setItem:(k,v)=>mem.set(k,v)},crypto:globalThis.crypto,console,Date,Math,Map,Set,Number,String,JSON,Promise});
vm.runInContext(code,context);
const run=s=>vm.runInContext(s,context);
const dates=['2026-03-20','2026-03-22','2026-04-11'];
context.fakeRows=dates.map((date,i)=>({date,student:'นักเรียน '+i,source:'Meet '+date+'.xlsx',course:'Biology',courseId:'',classLabel:'เดี่ยว',minutes:50+i,actual:55,timeRange:'12:00–12:55',before:600}));
assert.equal(run('summaryDateBreakdown(fakeRows).length'),3);
context.manyDays=Array.from({length:17},(_,i)=>({...context.fakeRows[0],date:'2026-03-'+String(i+1).padStart(2,'0')}));
assert.equal(run('summaryDateBreakdown(manyDays).length'),17);
assert.equal(run('summaryRowsTable(manyDays).match(/<time datetime=/g).length'),17);
const html=run('summaryRowsTable(fakeRows)');
assert.match(html,/วันที่เรียน/);
for(const date of dates)assert(html.includes(date),'missing date '+date);
assert.match(html,/20 มี\.ค\. 2569/);
run('showSaveSummary("17 files","pending",fakeRows,()=>{})');
assert.match(mockModal.innerHTML,/3 วัน/);
assert.match(mockModal.innerHTML,/ตรวจสอบ.*วันที่เรียนของทุกคาบ/);
assert.match(mockModal.innerHTML,/summary-confirm-btn" disabled/);
context.fakeRows.push({...context.fakeRows[0],date:''});
assert.throws(()=>run('showSaveSummary("bad","pending",fakeRows,()=>{})'),/ไม่มีวันที่เรียน/);
context.fakeRows.pop();
context.fakeRows.push({...context.fakeRows[0],date:'2026-02-30'});
assert.throws(()=>run('summaryDateBreakdown(fakeRows)'),/ไม่ถูกต้อง/);
assert.match(code,/sessions\.push\(\{id:sid,date:d\.date/,'Session persists source report date');
assert.match(code,/filename:d\.filename,date:d\.date/,'Imports persists source report date');
assert.match(code,/if\(!dateValid\(s\.date\)\)throw Error/,'Approval checks the saved date');
console.log('PASS explicit date column, 3 days, Thai+ISO display, invalid-date protection, Sessions+Imports persistence');
